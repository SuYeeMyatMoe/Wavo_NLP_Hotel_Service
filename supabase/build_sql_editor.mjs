// Rebuild the single-file SQL Editor installer from the canonical migrations.
import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const directory = path.dirname(fileURLToPath(import.meta.url));
function expand(file) {
  const source = readFileSync(file, 'utf8');
  return source.replace(/^\\set[^\n]*$/gm, '')
    .replace(/^\\ir\s+([^\r\n]+)\r?$/gm, (_, name) =>
      `-- Included: ${name.trim()}\n${expand(path.resolve(path.dirname(file), name.trim()))}`)
    .replace(/^BEGIN;\s*$/gm, '')
    .replace(/^COMMIT;\s*$/gm, '');
}
const sql = `-- WAVO: FRESH INSTALL FOR THE SUPABASE SQL EDITOR
-- Paste this entire file into a new SQL Editor query and run as postgres.
-- Generated by: node supabase/build_sql_editor.mjs
-- Includes tables, indexes, access policies, private storage and notification authorization.
-- Uses the private hotel schema. Keep it out of Data API exposed schemas.
-- Does not create Supabase Auth users, sample guests or real reservations.
-- Existing Wavo installations must use the incremental migrations instead.
BEGIN;
DO $wavo_fresh$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='hotel' AND table_type='BASE TABLE') THEN
    RAISE EXCEPTION 'Wavo tables already exist. Use incremental migrations; this file is for a fresh installation.';
  END IF;
END $wavo_fresh$;
${expand(path.join(directory, 'install.sql')).replace('-- Run with psql as the project database owner. The private schema is not exposed to PostgREST.', '')}
COMMIT;

-- A successful run returns the created table names and their RLS status.
SELECT c.relname AS table_name, c.relrowsecurity AS row_level_security
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='hotel' AND c.relkind='r'
ORDER BY c.relname;
`;
if (/^\\/m.test(sql)) throw new Error('Unexpanded psql command');
writeFileSync(path.join(directory, 'wavo_sql_editor.sql'), sql);
console.log('Generated supabase/wavo_sql_editor.sql');
